-- 0276: A director who has been away from a room is caught up by a short
-- summary of what they missed, written by a person's own Claude, so they can
-- rejoin the talk without reading every message.
--
-- chat_room_summaries holds one row per catch-up written for a room: the room
-- (tied to the same organisation by a composite key, on delete restrict, so a
-- room with a catch-up is never deleted), the moment of the last message it
-- covers (covers_up_to), its words (1 to 4000 characters), who wrote it (kept
-- with no foreign key, so the catch-up outlives the account, as a message's
-- author is) and how (written_via: through their Claude, as posted_via says of
-- a message), and when it was written. A catch-up is for everyone in the room,
-- never one person's own. The room shows the latest one to a reader who comes
-- back to unread messages; nothing is generated by the site, which calls no AI
-- model: a person's own Claude reads the room over the connector, writes the
-- catch-up and saves it with record_chat_summary.
--
-- Nothing written is ever edited or deleted: a newer catch-up is a new row,
-- and no policy lets anyone change one. The index serves the one question the
-- room and the connector ask: the latest catch-up of a room.
--
-- The limits mirror src/lib/data/chat/chatSummaryRules.ts, which the site
-- checks before anything is written, with the rule that covers_up_to is not
-- in the future and not later than the room's latest message.
--
-- That organisation's people read the catch-ups by the one module rule. No
-- policy lets the app write: the site writes through the service role after
-- its own check. Adds only: one table and two indexes. No row is updated. The
-- new key takes a short lock on chat_rooms, so the lock timeout gives up in
-- seconds rather than queue the live site behind it.

begin;

set local lock_timeout = '5s';
set local statement_timeout = '1min';

create table if not exists public.chat_room_summaries (
	id uuid primary key default gen_random_uuid(),
	organisation_id uuid not null,
	room_id uuid not null,
	covers_up_to timestamptz not null,
	words text not null check (char_length(words) between 1 and 4000),
	written_by_account_id uuid not null,
	written_via text not null default 'claude' check (written_via in ('site', 'claude')),
	created_at timestamptz not null default now(),
	foreign key (room_id, organisation_id)
		references public.chat_rooms (id, organisation_id) on delete restrict
);

create index if not exists chat_room_summaries_latest_of_room
	on public.chat_room_summaries (room_id, created_at desc);

create index if not exists chat_room_summaries_by_organisation
	on public.chat_room_summaries (organisation_id);

alter table public.chat_room_summaries enable row level security;

drop policy if exists "people read the chat catch-ups of their organisations" on public.chat_room_summaries;
create policy "people read the chat catch-ups of their organisations" on public.chat_room_summaries
	for select using (public.can_use_organisation_module(organisation_id, 'chat'));

commit;

notify pgrst, 'reload schema';
